export const LANGS = ['zh', 'en'];

/** Prefer the <html lang> js/theme-init.js stamped before first paint. */
function langFromDocument() {
  const raw = document.documentElement.getAttribute('lang') || '';
  return raw.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

let current = langFromDocument();

export function detectLang() {
  try {
    const stored = localStorage.getItem('cl-lang');
    if (stored && LANGS.includes(stored)) return stored;
  } catch {
    /* private mode */
  }
  const nav = (navigator.languages || [navigator.language || 'en']).join(',');
  return /\bzh\b|zh-/i.test(nav) ? 'zh' : 'en';
}

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : 'en';
  try {
    localStorage.setItem('cl-lang', current);
  } catch {
    /* private mode — the choice just will not persist */
  }
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
  return current;
}

export function lang() {
  return current;
}

export function t(key) {
  return STRINGS[current][key] ?? STRINGS.en[key] ?? key;
}

/** Category label, falling back to the registry's own label for unknown ids. */
export function categoryLabel(id, registryCategories = []) {
  const dict = CATEGORY_LABELS[current] || CATEGORY_LABELS.en;
  if (dict[id]) return dict[id];
  const found = registryCategories.find((c) => c.id === id);
  if (found) return current === 'zh' ? found.label_zh || found.label : found.label;
  return id;
}

/** Swap all `data-i18n*` marked nodes into the active language. */
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const key = el.dataset.i18n;
    // Keep inline markup (links) when the translation has no markup of its own.
    if (el.children.length && el.querySelector('a')) continue;
    el.textContent = t(key);
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
  }
  for (const el of root.querySelectorAll('[data-i18n-aria-label]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  }
  for (const el of root.querySelectorAll('[data-i18n-alt]')) {
    el.alt = t(el.dataset.i18nAlt);
  }
}

/** Tab title: bilingual site name, unchanged by language. */
const SITE_TITLE = 'Robot Description Gallery Online | 机器人3D模型在线合集';

export function pageTitle(prefix) {
  return prefix ? `${prefix} · ${SITE_TITLE}` : SITE_TITLE;
}

/**
 * Static chrome that must match `current` without waiting for a view to
 * re-render: marked nodes, and the language button (it names the language
 * you would switch *to*). The site-header title and tab title stay bilingual.
 */
export function applyChrome() {
  applyStatic();
  const button = document.getElementById('lang-toggle');
  if (button) {
    const label = button.querySelector('.lang-label');
    if (label) label.textContent = current === 'zh' ? t('lang.toEn') : t('lang.toZh');
    button.setAttribute('aria-label', current === 'zh' ? t('lang.switchToEn') : t('lang.switchToZh'));
  }
}

/** Show the page once the active language is on the static nodes. */
export function revealLang() {
  document.documentElement.classList.remove('i18n-pending');
}
